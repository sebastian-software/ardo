import fs from "node:fs/promises"
import path from "node:path"

export type GeneratedDoc = {
  path: string
  content: string
  frontmatter: {
    title: string
    description?: string
    sidebar_position?: number
    sidebar?: "leaf" | boolean
  }
}

const GENERATED_SENTINEL_FILE = ".ardo-generated"

export async function writeGeneratedDocs(
  options: { outputDir: string; out: string; configKey?: string },
  docs: GeneratedDoc[]
): Promise<void> {
  const directory = resolveGeneratedDocsDirectory(
    options.outputDir,
    options.out,
    options.configKey ?? "api.out"
  )
  await prepareGeneratedDocsDirectory(directory)
  await fs.mkdir(directory, { recursive: true })
  await fs.writeFile(path.join(directory, GENERATED_SENTINEL_FILE), "Generated by Ardo.\n")
  for (const doc of docs) {
    const file = path.join(directory, doc.path)
    await fs.mkdir(path.dirname(file), { recursive: true })
    const lines = ["---", `title: ${JSON.stringify(doc.frontmatter.title)}`]
    if (doc.frontmatter.description != null)
      lines.push(`description: ${JSON.stringify(doc.frontmatter.description)}`)
    if (doc.frontmatter.sidebar_position != null)
      lines.push(`sidebar_position: ${doc.frontmatter.sidebar_position}`)
    if (doc.frontmatter.sidebar === false) lines.push("sidebar: false")
    else if (doc.frontmatter.sidebar === "leaf") lines.push("sidebar: leaf")
    lines.push("---", "", doc.content)
    await fs.writeFile(file, lines.join("\n"))
  }
}

export function resolveGeneratedDocsDirectory(
  outputDir: string,
  out: string,
  configKey = "typedoc.out"
): string {
  const resolvedOutputDir = path.resolve(outputDir)
  const resolvedApiDirectory = path.resolve(resolvedOutputDir, out)
  const relativePath = path.relative(resolvedOutputDir, resolvedApiDirectory)
  if (relativePath === "" || relativePath.startsWith("..") || path.isAbsolute(relativePath)) {
    throw new Error(
      `[ardo] ${configKey} must resolve inside the routes directory, not to the routes directory itself or a parent directory: ${JSON.stringify(out)}`
    )
  }
  return resolvedApiDirectory
}

export async function prepareGeneratedDocsDirectory(directory: string): Promise<void> {
  if (!(await pathExists(directory))) return
  const sentinel = await pathExists(path.join(directory, GENERATED_SENTINEL_FILE))
  const entries = await fs.readdir(directory)
  if (!sentinel && entries.length > 0) {
    throw new Error(
      `[ardo] Refusing to delete ${directory} because it is not marked as Ardo-generated. Move your handwritten content elsewhere or remove the directory manually.`
    )
  }
  await fs.rm(directory, { force: true, recursive: true })
}

async function pathExists(file: string): Promise<boolean> {
  try {
    await fs.access(file)
    return true
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return false
    throw error
  }
}
