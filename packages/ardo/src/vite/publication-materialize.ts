import fs from "node:fs/promises"
import path from "node:path"
import type { ResolvedConfig } from "../config/types"
import type { Publication, PublicationConfig } from "../publication/types"
import { preparePublication, type PreparedPublication } from "./publication"

export const PUBLICATION_ID = "virtual:ardo/publication"
export const RESOLVED_PUBLICATION_ID = `\0${PUBLICATION_ID}`
const MARKER = ".ardo-publication"
export type PublicationBuilder = {
  options: PublicationConfig
  site: { resolvedConfig?: ResolvedConfig; routesDir: string }
  prepared: PreparedPublication[]
  publications: Record<string, Publication>
  sources: Map<string, string>
  queue: Promise<void>
}

export async function refreshPublication(builder: PublicationBuilder): Promise<void> {
  const config = builder.site.resolvedConfig
  if (config == null) throw new Error("[ardo] Publication configuration was not resolved.")
  const locales =
    config.i18n === false ? [undefined] : config.i18n.locales.map((locale) => locale.id)
  const prepared = await prepareAll(builder, { config, locales })
  const directories = locales.map((locale) =>
    path.resolve(builder.site.routesDir, locale ?? "", builder.options.to ?? "news")
  )
  await validateDirectories(directories, path.resolve(config.root, builder.options.from))
  const sources = await writeRoutes(directories, prepared)
  builder.prepared = prepared
  builder.sources = sources
  builder.publications = Object.fromEntries(
    prepared.map((entry, index) => [locales[index] ?? "default", entry.publication])
  )
}

async function prepareAll(
  builder: PublicationBuilder,
  input: { config: ResolvedConfig; locales: Array<string | undefined> }
): Promise<PreparedPublication[]> {
  const result = []
  const now = new Date()
  // Validate every locale and image before replacing any generated routes.
  for (const localeId of input.locales)
    result.push(
      await preparePublication({
        options: builder.options,
        config: input.config,
        routesDir: builder.site.routesDir,
        localeId,
        now,
      })
    )
  return result
}

async function validateDirectories(directories: string[], source: string): Promise<void> {
  for (const directory of directories) {
    if (isInside(source, directory) || isInside(directory, source))
      throw new Error("[ardo] Publication source and generated route directories must not overlap.")
    const existing = await fs.readdir(directory).catch((error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return [] as string[]
      throw error
    })
    if (existing.length > 0 && !existing.includes(MARKER))
      throw new Error(
        `[ardo] Refusing to replace handwritten publication routes in ${directory}. Choose another publication.to directory.`
      )
  }
}

async function writeRoutes(
  directories: string[],
  prepared: PreparedPublication[]
): Promise<Map<string, string>> {
  const sources = new Map<string, string>()
  for (const directory of directories) {
    await fs.rm(directory, { recursive: true, force: true })
    await fs.mkdir(directory, { recursive: true })
    await fs.writeFile(path.join(directory, MARKER), "Generated by Ardo.\n")
  }
  for (const publication of prepared) {
    for (const route of publication.routes) {
      await fs.mkdir(path.dirname(route.filePath), { recursive: true })
      await fs.writeFile(route.filePath, route.content)
      if (route.sourceFile != null) sources.set(route.filePath, route.sourceFile)
    }
  }
  return sources
}

export function isInside(file: string, directory: string): boolean {
  const relative = path.relative(directory, file)
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative))
}
